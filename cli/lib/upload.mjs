// ATTACHING A FILE, WITHOUT A FILE.
//
// "Upload a receipt and confirm it appears in the list" is one of the commonest sentences anybody
// wants to write about their own app, and until now this runner could not carry it out at all: the
// agent could see the control (a file input renders as a `button` in the accessibility tree) and
// clicking it did NOTHING — Playwright cancels a file chooser nobody is listening for, so the
// click returned "done", the agent looked at an unchanged page, and reported the upload feature
// broken. A silent no-op that produces a confident bug report about a working app is the worst
// shape a missing feature can take, so this file adds the action AND the note that stops the agent
// clicking these controls.
//
// THE HARD PART IS NOT setInputFiles. IT IS WHICH FILE.
//
// Playwright wants a path on disk. A test that names one — ~/Downloads/receipt.pdf, fixtures/a.png
// committed to the repo — is a test that runs on the laptop it was written on and nowhere else,
// and the entire premise of this product is that a sentence is the whole test: no test code, no
// fixtures directory, nothing written to your repository. So the file is FABRICATED, here, from
// the only statement of intent the page actually makes: the input's `accept` attribute.
//
//   accept="image/*"        → a real 16x16 PNG
//   accept=".pdf"           → a real one-page PDF
//   accept="text/csv"       → a two-row CSV
//   no accept at all        → a short text file
//
// Every one of those is generated byte-for-byte deterministically, which is what makes an upload
// step REPLAYABLE. The recording holds `{kind:"upload", role, name}` and no path and no bytes; at
// replay time the accept attribute is read off the live page again and the same file is rebuilt.
// Storing the fixture in the recording would have put a base64 blob in somebody's repository and
// made the recording lie the moment the app changed what it accepts.
//
// WHY THE IMAGES ARE BUILT AND NOT DOWNLOADED. There are no dependencies in this CLI, so there is
// no image library. The PNG is encoded here (CRC32, an Adler-32, and STORED deflate blocks rather
// than zlib's — deflateSync's output is not promised to be identical across zlib versions, and a
// fixture whose bytes drift between machines is not deterministic). The JPEG cannot be encoded in
// forty lines, so it is a constant: a 16x16 baseline JPEG produced once by Chromium's own encoder
// with its ICC profile stripped, 343 bytes, and browser.test-style tests DECODE it in a real
// browser rather than trusting this comment.

import { mkdirSync, renameSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import path from "node:path";
import { disabledDetail, fileSink, probeControl } from "./uploadsafe.mjs";

/**
 * Where fabricated files go. Never the repository, and never anywhere the app can see by accident.
 *
 * SCOPED TO THE USER. A fixed name under the system temp directory is a directory the FIRST account
 * to run this owns, at 0700, on every shared machine there is — a self-hosted CI runner, a build
 * box, a container that reuses /tmp across jobs. The second account then gets EACCES on the
 * mkdir/write, and because that arrives as a failed upload STEP it reads as a bug in the
 * application under test. Measured: `EACCES: permission denied, open
 * '/tmp/smolanalytics-uploads/smolanalytics-test.png.41958.tmp'` handed to the agent as the reason
 * an upload did not work. The uid costs nothing and the path stays stable per user, which is all
 * the replay path ever needed from it.
 */
const OWNER = typeof process.getuid === "function" ? `-${process.getuid()}` : "";
export const FIXTURE_DIR = path.join(tmpdir(), `smolanalytics-uploads${OWNER}`);

/**
 * The tool the agent is given. `ref` and nothing else: the model does not choose a path, a format
 * or a size, because every one of those is a way for it to invent a file the app then rejects and
 * for the rejection to read as a bug in the app.
 */
